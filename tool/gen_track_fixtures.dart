// Generates the synthetic GPS fixtures in test/fixtures/tracks/.
// Deterministic: `dart run tool/gen_track_fixtures.dart`.
// ignore_for_file: avoid_print

import 'dart:io';
import 'dart:math' as math;

const _r = 6371008.8;

double _haversine(double la1, double lo1, double la2, double lo2) {
  double rad(double d) => d * math.pi / 180;
  final a =
      math.pow(math.sin(rad(la2 - la1) / 2), 2) +
      math.cos(rad(la1)) *
          math.cos(rad(la2)) *
          math.pow(math.sin(rad(lo2 - lo1) / 2), 2);
  return 2 * _r * math.asin(math.sqrt(a));
}

class _Gen {
  new(int seed) : rnd = math.Random(seed);
  final math.Random rnd;
  double gauss() {
    final u = 1 - rnd.nextDouble();
    final v = rnd.nextDouble();
    return math.sqrt(-2 * math.log(u)) * math.cos(2 * math.pi * v);
  }
}

/// [speedAt] gives the true speed (m/s) at second t; spikes / bad fixes are
/// applied through [badAccuracy] and [spikeMeters].
void _track({
  required String name,
  required int seconds,
  required double Function(int t) speedAt,
  required int seed,
  required double headingAmp,
  Set<int> badAccuracy = const {},
  Map<int, double> spikeMeters = const {},
  String note = '',
}) {
  final g = _Gen(seed);
  var lat = 32.08;
  var lon = 34.78;
  var truthMeters = 0.0;
  var heading = 0.6;
  var nLat = 0.0;
  var nLon = 0.0;
  var nAlt = 0.0;
  const rho = 0.97;
  const sigma = 1.0;
  final w = sigma * math.sqrt(1 - rho * rho);
  final rows = <String>[];
  for (var t = 0; t <= seconds; t++) {
    if (t > 0) {
      final v = speedAt(t);
      heading += headingAmp * math.sin(t / 180) * 0.01;
      final dN = v * math.cos(heading);
      final dE = v * math.sin(heading);
      final nlat = lat + dN / _r * 180 / math.pi;
      final nlon =
          lon + dE / (_r * math.cos(lat * math.pi / 180)) * 180 / math.pi;
      truthMeters += _haversine(lat, lon, nlat, nlon);
      lat = nlat;
      lon = nlon;
    }
    nLat = rho * nLat + w * g.gauss();
    nLon = rho * nLon + w * g.gauss();
    nAlt = rho * nAlt + 0.5 * g.gauss();
    var rLat = lat + nLat / _r * 180 / math.pi;
    final rLon =
        lon + nLon / (_r * math.cos(lat * math.pi / 180)) * 180 / math.pi;
    var acc = 4 + g.rnd.nextDouble() * 6;
    final alt = 30 + 15 * math.sin(t / 400) + nAlt;
    if (badAccuracy.contains(t)) {
      acc = 40;
      rLat += 25 / _r * 180 / math.pi;
    }
    final spike = spikeMeters[t];
    if (spike != null) rLat += spike / _r * 180 / math.pi;
    final sp = math.max(0, speedAt(t) + 0.1 * g.gauss());
    rows.add(
      '${t * 1000},${rLat.toStringAsFixed(6)},${rLon.toStringAsFixed(6)},'
      '${alt.toStringAsFixed(1)},${acc.toStringAsFixed(1)},'
      '${sp.toStringAsFixed(2)}',
    );
  }
  final out = StringBuffer()
    ..writeln('# synthetic fixture, generated by tool/gen_track_fixtures.dart')
    ..writeln('# reference_distance_m=${truthMeters.toStringAsFixed(1)}');
  if (note.isNotEmpty) out.writeln(note);
  out
    ..writeln('t_ms,lat,lon,alt,accuracy,speed')
    ..writeAll(rows, '\n')
    ..writeln();
  File('test/fixtures/tracks/$name.csv').writeAsStringSync(out.toString());
  print('$name: ${rows.length} rows, ${truthMeters.toStringAsFixed(1)} m');
}

void main() {
  Directory('test/fixtures/tracks').createSync(recursive: true);
  // (a) 5 km at 5:20/km = 3.125 m/s -> 1600 s.
  _track(
    name: 'run_5k',
    seconds: 1600,
    speedAt: (t) => t == 0 ? 0 : 3.125,
    seed: 1,
    headingAmp: 1,
  );
  // (b) 30 km at 25 km/h = 6.944 m/s -> 4320 s.
  _track(
    name: 'ride_30k',
    seconds: 4320,
    speedAt: (t) => t == 0 ? 0 : 25 / 3.6,
    seed: 2,
    headingAmp: 0.6,
  );
  // (c) run with a 60 s stop (t 401..460), a 300 m spike at t=700 and
  // accuracy-40 fixes.
  _track(
    name: 'run_stop_spike',
    seconds: 1200,
    speedAt: (t) => t == 0 || (t > 400 && t <= 460) ? 0 : 3.125,
    seed: 3,
    headingAmp: 1,
    badAccuracy: {200, 201, 202, 900, 950},
    spikeMeters: {700: 300},
    note: '# stop_seconds=60 stop_from_s=400 stop_to_s=460 spike_at_s=700',
  );
}
